function generate_view_image($data, $no, $user_id = "", $endian = null, $spacing, $remarks)
{
    $r = "";
    try {
        if (@$data['has_photo'] == 1) {
            if (!empty(@$data['photo_name'])) {
                //   $r='<img width="542.4" height="399.36" src="'.base_url('').$data['photo_name'].'">';
                try {
                    //* UPDATE 22-09-2023 (Merubah image jadi base64 agar mencegah out of memory)
                    $image = "https://privaterepositorynas.alita.id/".$data['photo_name'];
                    $photos_image = '';

                    //* UPDATE 2023-11-05 (Ada yang iseng pake PDF buat ngirim gambar)
                    $position = stripos($data['photo_name'], 'pdf');

                    if ($position != false || !@getimagesize($image)) {
                        $photos_image = '';
                    } else {
                        $photos_image = '<img height="299" src="'.$image.'">';
                    }

                    // $photos_image = '<img height="299" src="https://privaterepositorynas.alita.id/' . $data['photo_name'] . '">';
                    $r = '<table style="margin:auto" cellspacing="1" cellpadding="1" width: 100%;><tbody>';
                    $r .= '<tr><td ><br><br><br><br><br><br>' . $spacing . '&nbsp;&nbsp;' . $data['checklist_name'] . '</td>';
                    $r .= $spacing . '&nbsp;&nbsp;' . '<td>' . $photos_image . '</td>';
                } catch (\Throwable $th) {
                    $r .= $spacing . '&nbsp;&nbsp;' . '<td height="500"><img width="542.4" height="299.36" src="http://eatp.alita.id/assets/images/noimage.jpg"></td>';
                }
                $r .= '</tr>';
                $r .= '</tbody></table>';
            } else {
                $r .= $spacing . '&nbsp;&nbsp;';
            }
        }
    } catch (\Throwable $e) {
        $r .= $spacing . '<img width="542.4" height="299.36" src="http://eatp.alita.id/assets/images/noimage.jpg">';
    }

    return $r;
}

function sub_render_image($parent, $pagebreak = "", $remarks, $iterasi, $user_id = "", $endian, $all_header = "", $pos = 0, $spacing = "")
{
    $header = '<p><strong>' . $spacing . $parent['group_name'] . '</strong></p>';

    if (isset($parent['sub_group'])) {
        $_2nd = 1;
        $loop_key = 0;
        foreach ($parent['sub_group'] as $gg) {
            // if ($gg['group_name'] != 'ODU ') {
            if ($loop_key == 0 && $pos == 0) {
                $all_header .= $header;
            } else {
                $all_header = $header;
            }
            sub_render_image($gg, $pagebreak, $remarks, false, $user_id, $endian, $all_header, $loop_key, $spacing . '&nbsp;&nbsp;');
            $loop_key++;
            // }
        }
    }
    if (isset($parent['checklists'])) {
        $i = 1;
        $checklists = "";
        if (@$parent['checklists'][0]['has_photo'] == "2") {
            $checklists = '<table style="margin:auto" border="1" cellspacing="1" cellpadding="1">
                    <tbody>';
            //Header
            $checklists .= '<tr bgcolor="#A9A9A9">';
            foreach ($parent['checklists'] as $tbheader) {
                $checklists .= '<td align="center">
                                <strong>' . $tbheader['checklist_name'] . '</strong>
                            </td>';
            }
            $checklists .= '</tr>';
            //Body
            $checklists .= '<tr>';
            foreach ($parent['checklists'] as $keys => $tbbody) {
                //* EDITED 14-11-2023 Ngecek image apakah kosong atau tidak
                if ($keys == 0) {
                    if (!empty($tbbody['image_sign'])) {
                        $image = "https://privaterepositorynas.alita.id/".@$tbbody['image_sign'];
                        if (@getimagesize($image)) {
                            $checklists .= '<td align="center"><img src="https://privaterepositorynas.alita.id/' . @$tbbody['image_sign'] . '" ></td>';
                        }
                        else {
                            $checklists .= '<td align="center"><img width="542.4" height="299.36" src="http://eatp.alita.id/assets/images/noimage.jpg"></td>';
                        }
                        // $checklists .= '<td align="center"><img src="https://privaterepositorynas.alita.id/' . @$tbbody['image_sign'] . '" ></td>';
                    }

                } else {
                    if (!empty($tbbody['fop_photo'])) {
                        $image = "https://privaterepositorynas.alita.id/".@$tbbody['fop_photo'];
                        if (@getimagesize($image)) {
                            $checklists .= '<td align="center"><img src="https://privaterepositorynas.alita.id/' . @$tbbody['fop_photo'] . '" ></td>';
                        }
                        else {
                            $checklists .= '<td align="center"><img width="542.4" height="299.36" src="http://eatp.alita.id/assets/images/noimage.jpg"></td>';
                        }
                        // $checklists .= '<td align="center"><img src="https://privaterepositorynas.alita.id/' . @$tbbody['fop_photo'] . '" ></td>';
                    }
                }
                //*
            }
            $checklists .= '</tr>';
            $checklists .= '</tbody></table>';
        } else {
            foreach ($parent['checklists'] as $cc) {
                //echo $cc['checklist_name']."<br/>";
                $checklists .= generate_view_image($cc, $i, $user_id, $endian, $spacing, $remarks);
