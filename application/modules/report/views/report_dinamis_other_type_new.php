<?php
function searchGroup($group_id, $group_array)
{
    $result = array();
    //Get Index Array
    $index = array_search($group_id, array_column($group_array, 'group_id'));

    if (isset($index)) {
        $result = $group_array[$index];
    }

    return $result;
}
